#!/bin/sh
# Provides frontend/js/helpers/config.js for the prebuilt GMT frontend image.
# The nginx base image runs this script on every container start, before nginx starts.
#
# There are two ways to configure the frontend:
#   1. Set the GMT_* environment variables below. config.js is then generated from
#      config.js.example on every start.
#   2. Mount your own config.js to $GMT_FRONTEND_ROOT/js/helpers/config.js. It is served as
#      it is and the GMT_* variables are ignored.
#
# Any invalid value stops the container, so a misconfiguration is not silently served.
set -eu

ME=$(basename "$0")
TEMPLATE=/usr/share/gmt-frontend/config.js.template
TARGET="${GMT_FRONTEND_ROOT}/js/helpers/config.js"
# First line of every generated file. A config.js without it was mounted by the user.
MARKER='// Generated by the GMT frontend container from the GMT_* environment variables. Changes are overwritten on start.'

log() {
    if [ -z "${NGINX_ENTRYPOINT_QUIET_LOGS:-}" ]; then
        echo "$ME: $*"
    fi
}

fail() {
    echo "$ME: ERROR: $*" >&2
    exit 1
}

if [ -d "$TARGET" ]; then
    fail "$TARGET is a directory. Docker creates one when the mounted config.js does not exist on the host."
fi

if [ -e "$TARGET" ] && [ "$(head -n 1 "$TARGET")" != "$MARKER" ]; then
    log "Using mounted $TARGET as it is. The GMT_* environment variables are ignored."
    if grep -qE '__[A-Z_]+__' "$TARGET"; then
        log "WARNING: The mounted config.js still contains placeholders like __API_URL__."
    fi
    exit 0
fi

NEWLINE='
'

# Prints the value as a sed replacement for the | delimiter. Rejects characters that would
# end the JavaScript string the value is put into.
url_value() {
    name=$1
    value=$2
    case "$value" in
        *\"* | *\\* | *"$NEWLINE"*)
            fail "$name must not contain double quotes, backslashes or newlines."
            ;;
    esac
    printf '%s' "$value" | sed -e 's/[|&]/\\&/g'
}

bool_value() {
    name=$1
    value=$(printf '%s' "$2" | tr '[:upper:]' '[:lower:]')
    case "$value" in
        true | 1 | yes) echo true ;;
        false | 0 | no) echo false ;;
        *) fail "$name must be true or false, but is '$2'." ;;
    esac
}

# Defaults match the defaults of install_linux.sh / install_mac.sh
api_url=$(url_value GMT_API_URL "${GMT_API_URL:-http://api.green-coding.internal:9142}")
metrics_url=$(url_value GMT_METRICS_URL "${GMT_METRICS_URL:-http://metrics.green-coding.internal:9142}")
elephant_url=$(url_value GMT_ELEPHANT_URL "${GMT_ELEPHANT_URL:-}")
activate_scenario_runner=$(bool_value GMT_ACTIVATE_SCENARIO_RUNNER "${GMT_ACTIVATE_SCENARIO_RUNNER:-true}")
activate_eco_ci=$(bool_value GMT_ACTIVATE_ECO_CI "${GMT_ACTIVATE_ECO_CI:-false}")
activate_carbon_db=$(bool_value GMT_ACTIVATE_CARBON_DB "${GMT_ACTIVATE_CARBON_DB:-false}")
activate_power_hog=$(bool_value GMT_ACTIVATE_POWER_HOG "${GMT_ACTIVATE_POWER_HOG:-false}")
activate_software_view=$(bool_value GMT_ACTIVATE_SOFTWARE_VIEW "${GMT_ACTIVATE_SOFTWARE_VIEW:-false}")
activate_ai_optimisations=$(bool_value GMT_ACTIVATE_AI_OPTIMISATIONS "${GMT_ACTIVATE_AI_OPTIMISATIONS:-false}")

{
    echo "$MARKER"
    sed \
        -e "s|__API_URL__|${api_url}|" \
        -e "s|__METRICS_URL__|${metrics_url}|" \
        -e "s|__ELEPHANT_URL__|${elephant_url}|" \
        -e "s|__ACTIVATE_SCENARIO_RUNNER__|${activate_scenario_runner}|" \
        -e "s|__ACTIVATE_ECO_CI__|${activate_eco_ci}|" \
        -e "s|__ACTIVATE_CARBON_DB__|${activate_carbon_db}|" \
        -e "s|__ACTIVATE_POWER_HOG__|${activate_power_hog}|" \
        -e "s|__ACTIVATE_SOFTWARE_VIEW__|${activate_software_view}|" \
        -e "s|__ACTIVATE_AI_OPTIMISATIONS__|${activate_ai_optimisations}|" \
        "$TEMPLATE"
} > "${TARGET}.tmp"

# A placeholder added to config.js.example must also be handled here
if grep -qE '__[A-Z_]+__' "${TARGET}.tmp"; then
    rm -f "${TARGET}.tmp"
    fail "config.js.example has placeholders this script does not fill in."
fi

chmod 644 "${TARGET}.tmp"
mv "${TARGET}.tmp" "$TARGET"

log "Generated $TARGET from the GMT_* environment variables"
